/* Word-picture tools (see design/pictures/PLAN.md). Loads the real app in jsdom, the way dev/voices.js does.
   Usage: node design/pictures/tools.js <command>
     inventory        writes design/pictures/words.json: every built-in vocab item, grouped by its first English meaning
     chunk [from] [n] prints n concepts (default 150) from words.json, one per line, for writing briefs.json
   More commands (check, words, shots) arrive with the picture kit. Ends with "ok", or lists FAIL lines and exits 1. */
const fs = require('fs');
const path = require('path');
const { JSDOM, ResourceLoader, VirtualConsole } = require('jsdom');
const ROOT = path.join(__dirname, '..', '..'), HERE = __dirname, BASE = 'https://parlance.test/';
const LEVELS = ['A1', 'A2', 'B1', 'B2', 'C1', 'C2'];
const sleep = ms => new Promise(r => setTimeout(r, ms));

class LocalOnly extends ResourceLoader { fetch(url){ if (!url.startsWith(BASE)) return null; const pr = fs.promises.readFile(path.join(ROOT, decodeURIComponent(url.slice(BASE.length).split('?')[0]))); pr.abort = () => {}; return pr; } }
/* loadApp(fn): runs fn(window.__parlance, window) in the loaded app and returns what it returns, then closes the page */
async function loadApp(fn){
  const page = fs.readFileSync(path.join(ROOT, 'index.html'), 'utf8');
  const dom = new JSDOM('<!doctype html><html><head><meta charset="utf-8"></head><body>' + page + '</body></html>', {
    url: BASE + 'index.html', runScripts: 'dangerously', resources: new LocalOnly(), pretendToBeVisual: true, virtualConsole: new VirtualConsole(),
    beforeParse(w){ w.matchMedia = () => ({ matches: false, addEventListener(){}, removeEventListener(){} }); w.scrollTo = () => {}; w.Element.prototype.scrollIntoView = function(){}; w.HTMLCanvasElement.prototype.getContext = () => null; }
  });
  await new Promise(r => { if (dom.window.document.readyState === 'complete') r(); else dom.window.addEventListener('load', r); });
  for (let i = 0; i < 100 && !dom.window.__parlance; i++) await sleep(20);
  if (!dom.window.__parlance) throw new Error('The app did not load in jsdom. Run npm test to see why.');
  try { return await fn(dom.window.__parlance, dom.window); } finally { dom.window.close(); }
}

/* the normalized first English meaning: lowercase, spacing evened out, "to " kept so "drink" and "to drink" stay apart */
const meaningKey = e => String(e).toLowerCase().replace(/[’']/g, "'").replace(/\s+/g, ' ').trim();
const slug = s => meaningKey(s).replace(/^to /, 'to-').replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');

async function inventory(){
  const rows = await loadApp(P => P.COURSE ? Object.entries(P.COURSE).flatMap(([lang, c]) => c.units.flatMap((u, ui) => u.lessons.map((l, li) => ({ lang, unit: ui, order: li, lesson: l.id, level: l.level, title: l.title,
    vocab: l.vocab.map(v => ({ t: v.t, e: v.e, g: v.g || null })) })))) : []);
  if (!rows.length) throw new Error('No lessons found in the app.');
  const groups = new Map();
  for (const l of rows) for (const v of l.vocab){
    const key = meaningKey(v.e[0]);
    if (!groups.has(key)) groups.set(key, { key, id: slug(v.e[0]), level: l.level, at: LEVELS.indexOf(l.level) * 100000 + l.unit * 100 + l.order, words: [] });
    const g = groups.get(key), at = LEVELS.indexOf(l.level) * 100000 + l.unit * 100 + l.order;
    if (at < g.at){ g.at = at; g.level = l.level; }
    g.words.push({ lang: l.lang, t: v.t, e: v.e, g: v.g, lesson: l.lesson, level: l.level });
  }
  const concepts = [...groups.values()].sort((a, b) => a.at - b.at || a.key.localeCompare(b.key)).map(({ at, ...g }) => g);
  const ids = new Map();
  for (const c of concepts){   // two meanings can slug alike ("e.g." vs "eg"): keep ids unique
    const n = (ids.get(c.id) || 0) + 1; ids.set(c.id, n); if (n > 1) c.id += '-' + n;
  }
  const byLevel = Object.fromEntries(LEVELS.map(L => [L, concepts.filter(c => c.level === L).length]));
  const out = { note: 'Generated by node design/pictures/tools.js inventory. Do not edit by hand.', concepts: concepts.length, byLevel, list: concepts };
  fs.writeFileSync(path.join(HERE, 'words.json'), JSON.stringify(out, null, 1) + '\n');
  console.log(concepts.length + ' concepts from ' + rows.reduce((n, l) => n + l.vocab.length, 0) + ' vocab items', JSON.stringify(byLevel));
  return out;
}

/* one line per concept: id | level | English | the words in each language (and gender) | first lesson */
function chunk(from = 0, n = 150){
  const f = path.join(HERE, 'words.json'); if (!fs.existsSync(f)) throw new Error('Run the inventory first.');
  const { list } = JSON.parse(fs.readFileSync(f, 'utf8'));
  list.slice(from, from + n).forEach((c, i) => {
    const by = { de: [], es: [], it: [] };
    for (const w of c.words) if (!by[w.lang].includes(w.t)) by[w.lang].push(w.t);
    console.log([from + i, c.id, c.level, c.words[0].lesson, c.key + (c.words[0].e.length > 1 ? ' [' + c.words[0].e.slice(1, 3).join('; ') + ']' : ''), 'de: ' + by.de.join(' / '), 'es: ' + by.es.join(' / '), 'it: ' + by.it.join(' / ')].join(' | '));
  });
  console.log('-- ' + Math.min(from + n, list.length) + ' of ' + list.length);
}

module.exports = { loadApp, inventory, chunk, meaningKey, slug, LEVELS, ROOT, HERE };
if (require.main === module){
  const [cmd, ...rest] = process.argv.slice(2);
  const run = { inventory: () => inventory(), chunk: () => chunk(+rest[0] || 0, +rest[1] || 150) }[cmd];
  if (!run){ console.log('Usage: node design/pictures/tools.js inventory | chunk [from] [n]'); process.exit(cmd ? 1 : 0); }
  Promise.resolve().then(run).then(() => console.log('ok'), e => { console.log('FAIL ' + (e && e.message || e)); process.exit(1); });
}
